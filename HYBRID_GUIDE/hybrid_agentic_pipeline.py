def anonymize_text_for_backtest(raw_text: str, ticker: str, cutoff_date: str) -> str:
    """Strips company names, tickers, and relative dates to eliminate LLM pre-training memory leakage."""
    sanitized = raw_text
    clean_ticker = ticker.replace(".NS", "").replace(".BO", "")

    # Common company name patterns
    name_patterns = [
        clean_ticker,
        r"Hero\s+MotoCorp", r"Hero\s+Honda", r"Hero",
        r"Cupid\s+Limited", r"Cupid",
        r"Modison\s+Metals", r"Modison\s+Limited", r"Modison",
        r"Reliance\s+Industries", r"Reliance",
        r"Tata\s+Motors", r"Tata\s+Consultancy", r"TCS"
    ]
    for pat in name_patterns:
        sanitized = re.sub(rf"\b{pat}\b", "[Target_Company_Alpha]", sanitized, flags=re.IGNORECASE)

    # Relative Year Masking
    if cutoff_date:
        cutoff_year = int(cutoff_date[:4])
        for y_offset in range(-5, 6):
            target_y = cutoff_year + y_offset
            if y_offset == 0:
                rep = "[Year_T]"
            elif y_offset < 0:
                rep = f"[Year_T{y_offset}]"
            else:
                rep = f"[Year_T+{y_offset}]"
            sanitized = re.sub(rf"\b{target_y}\b", rep, sanitized)

    return sanitized


