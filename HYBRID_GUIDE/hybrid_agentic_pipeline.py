def export_and_plot_results(output_dir: str, tickers: list, batch_train_dfs: list, batch_test_dfs: list,
                           batch_valuations: list, preds: np.ndarray, q10s: np.ndarray, q90s: np.ndarray,
                           mode: str, horizon: int):
    os.makedirs(output_dir, exist_ok=True)
    summary_catalog = []

    for i, ticker in enumerate(tickers):
        train_df = batch_train_dfs[i]
        test_df = batch_test_dfs[i]
        val_data = batch_valuations[i]
        pred = preds[i]
        q10 = q10s[i]
        q90 = q90s[i]
        last_price = float(train_df.iloc[-1]["Close"])

        last_date = train_df.index[-1]
        future_dates = [last_date + datetime.timedelta(days=d) for d in range(1, horizon + 1)]

        plt.figure(figsize=(14, 7), dpi=150)
        plt.style.use('seaborn-v0_8-whitegrid' if 'seaborn-v0_8-whitegrid' in plt.style.available else 'default')
        plt.plot(train_df.index[-40:], train_df["Close"].values[-40:], label="Historical Context", color="#1b365d", linewidth=2)
        plt.plot(future_dates, pred, label=f"Hybrid Weighted Forecast (Target: Rs. {val_data['fair_value_target']:.2f})", color="#6b29b2", linewidth=2.8)

        # Plot Scenarios if available
        if val_data.get("scenarios"):
            sc = val_data["scenarios"]
            k = val_data.get("sigmoid_steepness", 0.18)
            t0 = val_data.get("sigmoid_midpoint", horizon / 2.0)
            bear_path = [last_price + (1.0 / (1.0 + np.exp(-k * (h + 1 - t0)))) * (sc["bear"]["target_price"] - last_price) for h in range(horizon)]
            bull_path = [last_price + (1.0 / (1.0 + np.exp(-k * (h + 1 - t0)))) * (sc["bull"]["target_price"] - last_price) for h in range(horizon)]
            plt.plot(future_dates, bull_path, label=f"Bull Scenario (25% prob): Rs. {sc['bull']['target_price']:.0f}", color="#107c41", linestyle="-.", linewidth=1.8)
            plt.plot(future_dates, bear_path, label=f"Bear Scenario (25% prob): Rs. {sc['bear']['target_price']:.0f}", color="#d83b01", linestyle=":", linewidth=1.8)
            plt.fill_between(future_dates, bear_path, bull_path, color="#0078d4", alpha=0.10, label="Strict Scenario Envelope")
        else:
            plt.fill_between(future_dates, q10, q90, color="#6b29b2", alpha=0.15, label="80% Prediction Band (P10 - P90)")

        coverage_str = ""
        if mode == "backtest" and not test_df.empty:
            actuals = test_df["Close"].values[:len(pred)]
            actual_dates = test_df.index[:len(pred)]
            plt.plot(actual_dates, actuals, label="Actual Ground Truth Prices", color="#107c41", linewidth=2.5, marker="o", markersize=3)
            
            valid_mask = ~np.isnan(actuals) & ~np.isnan(pred[:len(actuals)])
            if valid_mask.any():
                clean_act = actuals[valid_mask]
                clean_pr = pred[:len(actuals)][valid_mask]
                mae = float(np.mean(np.abs(clean_pr - clean_act)))
                mape = float(np.mean(np.abs((clean_act - clean_pr) / clean_act)) * 100)
                metric_str = f"MAE: Rs. {mae:.2f} | MAPE: {mape:.2f}%"
            else:
                mae, mape = 0.0, 0.0
                metric_str = "Backtest (No valid ground truth ticks)"

            if val_data.get("scenarios"):
                in_env = np.sum((clean_act >= np.array(bear_path)[:len(clean_act)] * 0.90) & (clean_act <= np.array(bull_path)[:len(clean_act)] * 1.10))
                cov_pct = float((in_env / len(clean_act)) * 100)
                coverage_str = f" | Envelope Coverage: {cov_pct:.1f}%"
        else:
            mae, mape = None, None
            metric_str = "Live Forward Prediction"

        # Institutional Scorecard
        scorecard = None
        stop_loss_val = None
        if build_institutional_scorecard is not None:
            try:
                fund_d = {
                    "scenarios": val_data.get("scenarios") or {},
                    "weighted_target": val_data.get("fair_value_target", last_price),
                    "eps": val_data.get("trailing_eps"),
                    "sector_pe": val_data.get("sector_pe", 22.0)
                }
                try:
                    tk = yf.Ticker(ticker)
                    fund_d["industry"] = tk.info.get("industry") or tk.info.get("sector") or "General"
                except Exception:
                    fund_d["industry"] = "General"

                scorecard = build_institutional_scorecard(
                    ticker=ticker,
                    last_price=last_price,
                    fundamental_data=fund_d,
                    forecast_results={
                        "numerical_context": train_df["Close"].values[-64:].tolist() if not train_df.empty else [last_price]*10,
                        "weighted_expected": pred.tolist() if isinstance(pred, np.ndarray) else pred,
                        "base_q10": q10.tolist() if isinstance(q10, np.ndarray) else q10,
                        "base_q90": q90.tolist() if isinstance(q90, np.ndarray) else q90
                    },
                    horizon=horizon,
                    as_of=train_df.index[-1].strftime("%Y-%m-%d") if not train_df.empty else None
                )
                stop_loss_val = scorecard["institutional_risk_and_sizing"]["stop_loss_invalidation_level"]
            except Exception as e:
                print(f"  • [{ticker}] institutional_scorecard notice: {e}")

        anon_badge = "[BLIND-BOX ZERO LEAKAGE]" if mode == "backtest" else "[LIVE FORWARD]"
        if stop_loss_val:
            plt.axhline(y=stop_loss_val, color="#ea4335", linestyle="--", linewidth=1.8, label=f"Institutional Invalidation Stop (Rs. {stop_loss_val:.2f})")

        plt.title(f"{ticker} — Hybrid LLM + TimesFM 3.0 {anon_badge}\n{metric_str}{coverage_str}", fontsize=12, fontweight="bold")
        plt.xlabel("Date", fontsize=10, fontweight="bold")
        plt.ylabel("Price (INR)", fontsize=10, fontweight="bold")
        plt.legend(loc="upper left")
        plt.tight_layout()

        plot_path = os.path.join(output_dir, f"{ticker}_forecast_plot.png")
        plt.savefig(plot_path)
        plt.close()

        record = {
            "ticker": ticker,
            "mode": mode,
            "is_anonymized": (mode == "backtest"),
            "last_price": last_price,
            "fundamental_valuation": val_data,
            "terminal_prediction": float(pred[-1]),
            "p10_terminal": float(q10[-1]),
            "p90_terminal": float(q90[-1]),
            "plot_saved": plot_path
        }
        if mode == "backtest" and not test_df.empty:
            record["metrics"] = {"mae": mae, "mape": mape}
            if val_data.get("scenarios"):
                record["envelope_coverage_pct"] = cov_pct
        if scorecard:
            record["institutional_scorecard"] = scorecard

        json_path = os.path.join(output_dir, f"{ticker}_forecast_results.json")
        with open(json_path, "w") as f:
            json.dump(record, f, indent=2)

        summary_catalog.append(record)
        print(f"  • [{ticker}] Plot -> {plot_path}")
        print(f"  • [{ticker}] JSON -> {json_path}")
        if scorecard:
            print(f"  • [{ticker}] Institutional Directive: {scorecard['institutional_risk_and_sizing']['institutional_directive']}")

    summary_path = os.path.join(output_dir, "batch_portfolio_summary.json")
    with open(summary_path, "w") as f:
        json.dump(summary_catalog, f, indent=2)
    print(f"\n[Done] All batch results and plots saved to {output_dir}!")


def main():
    args = parse_arguments()

    if args.check:
        run_diagnostics()
        sys.exit(0)

    tickers = resolve_tickers(args.tickers)
    print(f"=================================================================")
    print(f" HYBRID LLM + EXA + TIMESFM 3.0 FORECASTING ENGINE")
    print(f" Mode: {args.mode.upper()} | Tickers: {len(tickers)} | Horizon: {args.horizon} days")
    if args.mode == "backtest":
        print(f" Zero-Leakage: ACTIVE (Blind-Box Entity Masking + 3-Branch Scenario Tree)")
    print(f"=================================================================")

    # Load Agent Harness Scenario if provided (Non-API Hybrid Mode)
    scenario_data = {}
    if args.scenario and os.path.exists(args.scenario):
        with open(args.scenario) as f:
            scenario_data = json.load(f)
        print(f"\n[Agent Harness Non-API Mode] Loaded external scenario: {args.scenario}")

    batch_train_dfs = []
    batch_test_dfs = []
    batch_valuations = []

    for ticker in tickers:
        train_df, test_df, last_price = fetch_market_data(ticker, args.mode, args.cutoff, args.horizon)
        
        if args.scenario and (ticker in scenario_data or "fair_value_target" in scenario_data):
            val_data = scenario_data.get(ticker, scenario_data)
            print(f"  • Using Agent Harness Scenario for {ticker}: Fair Value Target = Rs. {val_data['fair_value_target']:.2f}")
        else:
            exa_data = fetch_exa_intelligence(ticker, args.exa_key, args.mode, args.cutoff)
            pdf_path = resolve_pdf_for_ticker(args.pdf, ticker)
            filing_text = extract_filing_pdf(pdf_path)
            val_data = synthesize_fundamental_valuation(ticker, filing_text, exa_data, last_price,
                                                        args.api_provider, args.api_key, args.horizon,
                                                        args.mode, args.cutoff)

        batch_train_dfs.append(train_df)
        batch_test_dfs.append(test_df)
        batch_valuations.append(val_data)

    preds, q10s, q90s = execute_hybrid_forecaster(batch_train_dfs, batch_valuations, args.horizon)
    export_and_plot_results(args.output_dir, tickers, batch_train_dfs, batch_test_dfs,
                           batch_valuations, preds, q10s, q90s, args.mode, args.horizon)


if __name__ == "__main__":
    main()
